#!/usr/bin/env python3
"""mkcomplex.py > libtest-complex.inc - the points and the reference values for the section 'complex' of libtest.c: for each complex function of <complex.h> random points (log-uniform in size from 1e-3 to 1e3, the others near
the real and imaginary axes and near +-1 and +-i, away from the branch cuts) with the value that Python's cmath gives (accurate to about 1e-15).  The numbers are hexadecimal floats: exact.  The seed is fixed:
the file is the same every time."""
import cmath, math, random, sys
random.seed(20261011)
def hexf(x): return float(x).hex()
def pts(n):
    out = []
    for i in range(n):
        k = i % 5
        if k < 3:
            r = 10 ** random.uniform(-3, 3); a = random.uniform(-math.pi, math.pi)
            z = cmath.rect(r, a)
        elif k == 3:                                                     # near the real axis or the imaginary axis (but not on it)
            r = 10 ** random.uniform(-2, 2)
            z = complex(random.choice((-1, 1)) * r, random.choice((-1, 1)) * r * 10 ** random.uniform(-6, -2)) if random.random() < 0.5 else complex(random.choice((-1, 1)) * r * 10 ** random.uniform(-6, -2), random.choice((-1, 1)) * r)
        else:                                                            # near +-1 and +-i
            c = random.choice((1, -1, 1j, -1j))
            z = c + complex(random.uniform(-0.2, 0.2), random.uniform(-0.2, 0.2)) * 10 ** random.uniform(-4, 0)
        if z.imag == 0 or z.real == 0: z += 1e-9
        out.append(z)
    return out
def good(f, z):
    try: v = f(z)
    except (OverflowError, ValueError, ZeroDivisionError): return False
    return abs(v) < 1e300 and abs(v) > 1e-300
FUNCS = [("cexp", cmath.exp), ("clog", cmath.log), ("csqrt", cmath.sqrt), ("csin", cmath.sin), ("ccos", cmath.cos), ("ctan", cmath.tan), ("csinh", cmath.sinh), ("ccosh", cmath.cosh), ("ctanh", cmath.tanh),
         ("casin", cmath.asin), ("cacos", cmath.acos), ("catan", cmath.atan), ("casinh", cmath.asinh), ("cacosh", cmath.acosh), ("catanh", cmath.atanh)]
N = 60
print("/* generated by mkcomplex.py: points and values of cmath for the section 'complex' of libtest.c */")
print("struct cx_case { double zr, zi, wr, wi, er, ei; };")
for name, f in FUNCS:
    print("static const struct cx_case cx_%s[%d] = {" % (name, N))
    zs = [z for z in pts(4 * N) if good(f, z)][:N]
    assert len(zs) == N, name
    for z in zs:
        v = f(z)
        print("  { %s, %s, 0, 0, %s, %s }," % (hexf(z.real), hexf(z.imag), hexf(v.real), hexf(v.imag)))
    print("};")
print("static const struct cx_case cx_cpow[%d] = {" % N)
for z, w in zip(pts(N), pts(N)[::-1]):
    w = w / (abs(w) + 1) * 4                                              # moderate exponents: the result is finite
    v = z ** w
    print("  { %s, %s, %s, %s, %s, %s }," % (hexf(z.real), hexf(z.imag), hexf(w.real), hexf(w.imag), hexf(v.real), hexf(v.imag)))
print("};")
print("static const struct cx_case cx_cabs[%d] = {" % N)
for z in pts(N):
    print("  { %s, %s, 0, 0, %s, %s }," % (hexf(z.real), hexf(z.imag), hexf(abs(z)), hexf(cmath.phase(z))))
print("};")
