#!/usr/bin/env python3
"""mkgamma.py > libtest-gamma.inc - the points and the reference values for the section 'gamma' of libtest.c: erf, erfc, lgamma and tgamma at random points (erf and erfc up to the underflow of erfc, lgamma and tgamma
on both sides of the poles and close to them) with the values that Python's math module gives (erf and erfc: the host's libm; lgamma and gamma: accurate to about 1e-15).  The numbers are hexadecimal floats: exact."""
import math, random
random.seed(20261013)
def hexf(x): return float(x).hex()
rows = []
for i in range(400):
    k = i % 8
    if k < 3: x = random.uniform(-3, 3)
    elif k == 3: x = random.uniform(-8, 8)
    elif k == 4: x = random.uniform(0, 27)
    elif k == 5: x = 10 ** random.uniform(-12, 0) * random.choice((-1, 1))
    elif k == 6: x = random.uniform(-40, 175)
    else: x = random.choice((1, 2, 3, -1, -2, -3, -10, 0.5, -0.5, 5, 170, -170)) + 10 ** random.uniform(-12, -1) * random.choice((-1, 1))
    try: e = math.erf(x); ec = math.erfc(x)
    except Exception: e = ec = float("nan")
    try: lg = math.lgamma(x)
    except Exception: lg = float("nan")
    try: tg = math.gamma(x)
    except Exception: tg = float("nan")
    if not (abs(tg) < 1e300 and (tg == 0 or abs(tg) > 1e-300)): tg = float("nan")
    rows.append((x, e, ec, lg, tg))
print("/* generated by mkgamma.py: points and values of Python's math module for the section 'gamma' of libtest.c (a NaN: not checked) */")
print("struct gm_case { double x, erf, erfc, lgamma, tgamma; };")
print("static const struct gm_case gm_cases[%d] = {" % len(rows))
for r in rows:
    print("  { %s }," % ", ".join((hexf(v) if v == v else "NAN") for v in r))
print("};")
