# gen-iconv-tables.py OUTFILE: writes crt/posix/iconv_tables.h (the upper halves of the 8-bit sets of iconv.c, from Python's codecs)
import codecs
sets = [("ISO-8859-2","iso8859-2",["ISO88592","LATIN2","L2"]),("ISO-8859-3","iso8859-3",["ISO88593","LATIN3","L3"]),
("ISO-8859-4","iso8859-4",["ISO88594","LATIN4","L4"]),("ISO-8859-5","iso8859-5",["ISO88595","CYRILLIC"]),
("ISO-8859-7","iso8859-7",["ISO88597","GREEK"]),("ISO-8859-9","iso8859-9",["ISO88599","LATIN5","L5"]),
("ISO-8859-10","iso8859-10",["ISO885910","LATIN6","L6"]),("ISO-8859-13","iso8859-13",["ISO885913","LATIN7","L7"]),
("ISO-8859-14","iso8859-14",["ISO885914","LATIN8","L8"]),("ISO-8859-15","iso8859-15",["ISO885915","LATIN9","L9","LATIN-9"]),
("ISO-8859-16","iso8859-16",["ISO885916","LATIN10","L10"]),("WINDOWS-1250","cp1250",["CP1250"]),("WINDOWS-1251","cp1251",["CP1251"]),
("WINDOWS-1252","cp1252",["CP1252"]),("WINDOWS-1253","cp1253",["CP1253"]),("WINDOWS-1254","cp1254",["CP1254"]),("WINDOWS-1257","cp1257",["CP1257"]),
("CP437","cp437",["IBM437","437"]),("CP850","cp850",["IBM850","850"]),("CP858","cp858",["IBM858"]),("CP866","cp866",["IBM866","866"]),
("KOI8-R","koi8_r",["KOI8R"]),("KOI8-U","koi8_u",["KOI8U"])]
# RISC OS Latin1 (Alphabet 101): ISO 8859-1 plus Acorn's 0x80-0x9F
ro = {0x80:0x20AC,0x81:0x0174,0x82:0x0175,0x85:0x0176,0x86:0x0177,0x8C:0x2026,0x8D:0x2122,0x8E:0x2030,0x8F:0x2022,
0x90:0x2018,0x91:0x2019,0x92:0x2039,0x93:0x203A,0x94:0x201C,0x95:0x201D,0x96:0x201E,0x97:0x2013,0x98:0x2014,0x99:0x2212,
0x9A:0x0152,0x9B:0x0153,0x9C:0x2020,0x9D:0x2021,0x9E:0xFB01,0x9F:0xFB02}
out=["/* generated by gen-iconv-tables.py: the upper half (0x80-0xFF) of the 8-bit character sets of iconv.c; 0xFFFF = not assigned */"]
names=[]
def emit(cname,tab):
    out.append("static const unsigned short cs_%s[128] = {"%cname)
    for i in range(0,128,8): out.append("  "+",".join("0x%04X"%v for v in tab[i:i+8])+",")
    out.append("};")
tabs=[]
for canon,py,al in sets:
    t=[]
    for b in range(0x80,0x100):
        try:
            c=bytes([b]).decode(py); assert len(c)==1; t.append(ord(c))
        except Exception: t.append(0xFFFF)
    cn=canon.replace("-","_"); emit(cn,t); tabs.append((canon,cn,al))
t=[ro.get(b,b) if b<0xA0 else b for b in range(0x80,0x100)]
emit("RISCOS_LATIN1",t); tabs.append(("RISCOS-LATIN1","RISCOS_LATIN1",["RISCOSLATIN1","ALPHABET101","RISCOS"]))
out.append("static const struct cs_8bit { const char *name; const unsigned short *hi; } cs_list[] = {")
for canon,cn,al in tabs: out.append('  { "%s", cs_%s },'%(canon.replace("-",""),cn))
out.append("};")
out.append("static const struct { const char *alias; const char *name; } cs_alias[] = {")
for canon,cn,al in tabs:
    for a in al: out.append('  { "%s", "%s" },'%(a,canon.replace("-","")))
out.append("};")
open(__import__("sys").argv[1],"w").write("\n".join(out)+"\n")
