#!/bin/bash
# gen-locale-data.sh OUTFILE [LOCALE...]: writes sdk/crt/posix/locale_tab.h, the data of the locales of UnixLib 64 (day and month names, date and time formats, numbers, currency, yes/no),
# taken from the glibc of this machine (locale-dump.c); locales that are not installed are compiled with localedef from /usr/share/i18n.  Run on a Linux host with glibc and localedef.
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=$1; shift
LIST=${*:-"en_US en_GB en_AU en_CA en_IE en_NZ en_ZA en_IN de_DE de_AT de_CH fr_FR fr_CA fr_BE fr_CH es_ES es_MX it_IT nl_NL nl_BE pt_PT pt_BR sv_SE da_DK nb_NO fi_FI pl_PL cs_CZ ru_RU hu_HU el_GR tr_TR ca_ES cy_GB ga_IE gd_GB"}
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
gcc -w -o "$W/dump" "$HERE/locale-dump.c"
mkdir -p "$W/lp"
for l in $LIST; do localedef -i "$l" -f UTF-8 "$W/lp/$l.UTF-8" 2>/dev/null || true; done
{
  echo "/* generated by tools/gen-locale-data.sh from glibc: do not edit */"
  for l in $LIST; do LOCPATH="$W/lp" "$W/dump" "$l"; done
} > "$OUT"
