#!/usr/bin/env python3
# gen-collate-data.py [OUTFILE [iso14651_t1_common]]: writes sdk/crt/posix/collate_tab.h, the collation weights of the characters below U+3000 (and the ligatures of U+FB00..FB4F) of
# glibc's ISO 14651 table (/usr/share/i18n/locales/iso14651_t1_common), in a form that collate.c compares in four levels: base letters, accents, case, the position of the character in the table (the fourth level; punctuation has no weight at the first three).
import re, sys
out = sys.argv[1] if len(sys.argv) > 1 else "collate_tab.h"
src = sys.argv[2] if len(sys.argv) > 2 else "/usr/share/i18n/locales/iso14651_t1_common"
LIMIT = 0x3000
EXTRA = range(0xFB00, 0xFB50)
lines = open(src, encoding="utf-8").read().split("\n")
# positions: every bare <SYMBOL> line and every <Uxxxx> weights line takes the next position in the sequence
pos = {}
n = 0
entries = []
bare = re.compile(r"^(<[^>\s]+>)\s*(%.*)?$")
chr_line = re.compile(r"^<U([0-9A-F]+)>\s+(.*)$")
inside_lc = False
for ln in lines:
    if ln.startswith("LC_COLLATE"): inside_lc = True
    if not inside_lc: continue
    m = bare.match(ln)
    if m and ln[0] == "<":
        pos.setdefault(m.group(1), n); n += 1; continue
    m = chr_line.match(ln)
    if m:
        cp = int(m.group(1), 16)
        pos.setdefault("<U%s>" % m.group(1), n); n += 1
        rest = m.group(2).split("%")[0].strip()
        entries.append((cp, rest))
def fields(rest):
    # four fields separated by ';' outside quotes
    f, cur, q = [], "", False
    for c in rest:
        if c == '"': q = not q; cur += c
        elif c == ';' and not q: f.append(cur.strip()); cur = ""
        else: cur += c
    f.append(cur.strip())
    return f
def syms(x):
    if x == "IGNORE": return []
    return re.findall(r"<[^>]+>", x)
tab = {}
fourth = {}
for cp, rest in entries:
    if not (cp < LIMIT or cp in EXTRA): continue
    f = fields(rest)
    if len(f) < 3: continue
    ws = [syms(f[0]), syms(f[1]), syms(f[2])]
    w4 = syms(f[3]) if len(f) > 3 else []
    try:
        ranks = [[pos[s] for s in w] for w in ws]
    except KeyError:
        continue
    r4 = pos.get(w4[0], pos.get('<U%04X>' % cp)) if w4 else pos.get('<U%04X>' % cp)
    if r4 is None: continue
    tab[cp] = ranks
    fourth[cp] = r4
# dense numbers per level, in rank order (kept as small numbers so that a weight needs two bytes of base 254)
dense = []
for lv in range(3):
    used = sorted({r for cp in tab for r in tab[cp][lv]})
    dense.append({r: i + 1 for i, r in enumerate(used)})
    assert len(used) < 254 * 254 - 2, len(used)
rank4 = {c: i + 1 for i, c in enumerate(sorted(fourth, key=lambda c: fourth[c]))}
assert len(rank4) < 254 * 254 - 2
pool, index = [], []
for cp in sorted(tab):
    off = len(pool)
    for lv in range(3):
        w = [dense[lv][r] for r in tab[cp][lv]]
        pool.append(len(w)); pool.extend(w)
    index.append((cp, off))
o = ["/* generated by tools/gen-collate-data.py from glibc's iso14651_t1_common: do not edit.  %d characters, %d words of weights; level 1 has %d weights, level 2 %d, level 3 %d. */" % (len(index), len(pool), len(dense[0]), len(dense[1]), len(dense[2]))]
o.append("#define COLL_NCHARS %d" % len(index))
o.append("static const unsigned short coll_cp[COLL_NCHARS] = {")
for i in range(0, len(index), 12): o.append("  " + ",".join("0x%04X" % c for c, _ in index[i:i+12]) + ",")
o.append("};")
assert len(pool) < 65536
o.append("static const unsigned short coll_off[COLL_NCHARS] = {")
for i in range(0, len(index), 12): o.append("  " + ",".join("%d" % off for _, off in index[i:i+12]) + ",")
o.append("};")
o.append("static const unsigned short coll_rank[COLL_NCHARS] = {")
for i in range(0, len(index), 12): o.append("  " + ",".join("%d" % rank4[c] for c, _ in index[i:i+12]) + ",")
o.append("};")
o.append("static const unsigned short coll_pool[%d] = {" % len(pool))
for i in range(0, len(pool), 16): o.append("  " + ",".join("%d" % v for v in pool[i:i+16]) + ",")
o.append("};")
open(out, "w").write("\n".join(o) + "\n")
print(o[0])
