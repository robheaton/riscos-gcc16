#!/usr/bin/env python3
"""cmunge64 - CMHG file -> the header of a 64-bit module (AArch64 assembler) and the C header, for the modules of the kit (aarch64-riscos-gcc -mmodule).

  cmunge64.py [-p] [-D<sym>[=<val>]] [-U<sym>] [-I<dir>] [-s FILE.S] [-d FILE.h] [-o FILE.o] FILE.cmhg

The same CMHG language and the same C header as modkit/bin/cmunge (the 32-bit one: the parser and the C header are those of modkit/bin/mkmodhdr.py), with the AArch64 header: the words of the module
header, the strings and the tables of the commands, the SWI names and the service numbers, and small stubs that give the kit's entry points (modkit64.h: module_init, module_swi ...) the names of the
handlers of the CMHG file.  The rest (the relocator, the veneers, the zero-initialised area, errors copied to the RMA) is the kit's modcore64.S, which the header file includes.
Supported: title-string, help-string, date-string, initialisation-code, finalisation-code, service-call-handler (with or without service numbers), command-keyword-table (a handler for the table, handler: and
no-handler: for a command), swi-chunk-base-number, swi-decoding-table (with NAME/FN), swi-handler-code, international-help-file, module-is-not-reentrant.  Also supported: swi-decoding-code (one function, or NAME/NUMBER: modkit64.h) and error-identifiers (error blocks in the module; the kit copies them to the RMA when they are returned). Not yet (refused with a message):
the veneers (irq-handlers, vector-handlers, generic-veneers, vector-traps, event-handler: the kernel's conventions are not known), pdriver-handler, module-is-runnable, module-is-c-plus-plus.
  -p      run the C preprocessor over the file first (-D, -U and -I go to it)
  -o FILE the object: the header assembled with the options of the kit (aarch64-none-elf-gcc on PATH or in A64, default /var/tmp/a64/prefix/bin); with CMUNGE64_CC=aarch64-riscos-gcc in the environment
          that compiler is used, with -mmodule (it knows the options and the include folders itself)"""
import os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.realpath(__file__))
A64 = os.environ.get("A64", "/var/tmp/a64/prefix/bin")
CC = os.path.join(A64, "aarch64-none-elf-gcc")
MODCC = os.environ.get("CMUNGE64_CC")             # a compiler that knows -mmodule (the real target's aarch64-riscos-gcc, or the SDK's wrapper): it is used for the object, with -mmodule, instead of CC with the options of modflags.sh

def load_mkmodhdr():
    path = os.path.join(HERE, "..", "..", "modkit", "bin", "mkmodhdr.py")
    if not os.path.exists(path): sys.exit("cmunge64: modkit/bin/mkmodhdr.py is not there (looked in %s)" % path)
    src = open(path, encoding="utf-8").read()
    src = src[:src.rindex("\nmain()")]                                 # (the file runs main () at the end: take the functions only)
    ns = {"__file__": os.path.abspath(path), "__name__": "mkmodhdr"}
    exec(compile(src, path, "exec"), ns)
    return ns

def generate_asm(mk, m, src):
    asm_bytes, help_line = mk["asm_bytes"], mk["help_line"]
    title = m["title"]
    o = []
    A = o.append
    cmds = m["commands"] or []
    per_swi = any(h is not None for h in m["swi_handlers"])
    has_swi = m["swi_handler"] is not None or per_swi
    has_svc = m["service"] is not None
    nums = sorted(set(m["service_numbers"]))
    A("/* Generated by cmunge64.py from %s.  The header of a 64-bit module for the kit.  DO NOT EDIT. */" % os.path.basename(src))
    A("\t.section .text.header, \"ax\"\n\t.global\t_mod_start\n\t.hidden\t_mod_start\n_mod_start:")
    A("\t.word\t0\t\t\t\t\t/* 00 start entry: none */")
    A("\t.word\t(__mod_init_v - _mod_start) | 0x40000000\t/* 04 initialisation (bit 30: not ARM) */")
    A("\t.word\t__mod_final_v - _mod_start\t\t/* 08 finalisation */")
    A("\t.word\t%s\t\t/* 0C service call handler */" % ("mod_service - _mod_start" if has_svc else "0"))
    A("\t.word\ttitle - _mod_start\n\t.word\thelp - _mod_start")
    A("\t.word\t%s\t\t\t/* 18 commands */" % ("cmdtab - _mod_start" if cmds else "0"))
    A("\t.word\t%#x\t\t\t\t/* 1C SWI chunk base */" % (m["swi_chunk"] if has_swi else 0))
    A("\t.word\t%s\t\t/* 20 SWI handler */" % ("__mod_swi_v - _mod_start" if has_swi else "0"))
    notable = bool(m.get("swi_notable"))
    share = bool(has_swi and m["swi_prefix"] and m["swi_prefix"].lower() == title.lower() and not notable)
    A("\t.word\t%s\t\t/* 24 SWI decoding table */" % ("title - _mod_start" if share else "swi_table - _mod_start" if has_swi and m["swi_prefix"] and not notable else "0"))
    A("\t.word\t%s" % ("__mod_decode_v - _mod_start\t\t/* 28 SWI decoding code */" if m["swi_decoder"] else "0\t\t\t\t\t/* 28 SWI decoding code: none */"))
    A("\t.word\t%s\t\t/* 2C messages file */" % ("msgfile - _mod_start" if m["mfile"] is not None else "0"))
    A("\t.word\tmod_flags - _mod_start\t\t\t/* 30 offset to the module flags */")
    A("title:\n\t.asciz\t\"%s\"" % title)
    if share:
        for n in m["swi_names"]: A("\t.asciz\t\"%s\"" % n)
        A("\t.byte\t0\t\t\t\t\t/* end of the SWI table */")
    A("help:\n" + asm_bytes(help_line(m).encode("latin-1")) + "\n\t.byte\t0\n\t.balign\t4")
    if m["mfile"] is not None: A("msgfile:\n" + asm_bytes(m["mfile"]) + "\n\t.byte\t0\n\t.balign\t4")
    if has_swi and m["swi_prefix"] and not share and not notable:
        A("swi_table:\n\t.asciz\t\"%s\"" % m["swi_prefix"])
        for n in m["swi_names"]: A("\t.asciz\t\"%s\"" % n)
        A("\t.byte\t0\n\t.balign\t4")
    if cmds:
        for i, c in enumerate(cmds):
            if c["help"] is not None:
                if c["add_syntax"] and c["syntax"] is not None: A("ht%d:\n%s" % (i, asm_bytes(c["help"])))
                else: A("ht%d:\n%s\n\t.byte\t0" % (i, asm_bytes(c["help"])))
            if c["syntax"] is not None: A("is%d:\n%s\n\t.byte\t0" % (i, asm_bytes(c["syntax"])))
        A("\t.balign\t4\ncmdtab:")
        for i, c in enumerate(cmds):
            info = c["min"] | (c["gstrans"] << 8) | (c["max"] << 16) | (int(c["fs"]) << 31) | (int(c["status"]) << 30) | (int(c["intl"]) << 28)
            A("\t.asciz\t\"%s\"\n\t.balign\t4" % c["name"])
            A("\t.word\t%s" % ("0\t\t\t\t\t/* no handler (no-handler:) */" if c["nohandler"] else "cmd%d - _mod_start" % i))
            A("\t.word\t%#x\t\t\t\t/* min %d, max %d parameters */" % (info, c["min"], c["max"]))
            A("\t.word\t%s" % ("is%d - _mod_start" % i if c["syntax"] is not None else "0"))
            A("\t.word\t%s" % ("ht%d - _mod_start" % i if c["help"] is not None else "0"))
        A("\t.word\t0\t\t\t\t\t/* end of the table */")
    A("\t.balign\t4\nmod_flags:\n\t.word\t0x14\t\t\t\t\t/* bit 0 clear; bit 2: a zero-init size follows; bits 4-7 = 1: AArch64 */\n\t.word\t__ZISize")
    # commands: a stub for each command sets the number; module_command (the kit's entry: x0 = number, x1 = arguments, x2 = count, x3 = private word) calls the handler of the CMHG file as FN (args, count, number, pw)
    handled = [(i, c) for i, c in enumerate(cmds) if not c["nohandler"]]
    if handled:
        for i, c in handled: A("cmd%d:\tmov\tx2, #%d\n\tb\t__mod_cmd_v" % (i, i))
        A("\t.global\tmodule_command\n\t.hidden\tmodule_command\n\t.type\tmodule_command, %function\nmodule_command:\t\t\t\t\t/* x0 = command, x1 = args, x2 = argc, x3 = pw  ->  FN (args, argc, command, pw) */")
        A("\tmov\tx4, x0\n\tmov\tx0, x1\n\tmov\tx1, x2\n\tmov\tx2, x4")
        default = m["cmd_handler"]
        for i, c in handled:
            if c["handler"] and c["handler"] != default: A("\tcmp\tw4, #%d\n\tb.ne\t1f\n\tb\t%s\n1:" % (i, c["handler"]))
        if default: A("\tb\t%s" % default)
        else: A("\tmov\tx0, #0\n\tret")
    # init / final: the same arguments as the kit's
    if m["init"]: A("\t.global\tmodule_init\n\t.hidden\tmodule_init\n\t.type\tmodule_init, %%function\nmodule_init:\n\tb\t%s" % m["init"])
    if m["final"]: A("\t.global\tmodule_final\n\t.hidden\tmodule_final\n\t.type\tmodule_final, %%function\nmodule_final:\n\tb\t%s" % m["final"])
    if has_svc: A("\t.global\tmodule_service\n\t.hidden\tmodule_service\n\t.type\tmodule_service, %%function\nmodule_service:\n\tb\t%s" % m["service"])
    if has_swi:
        A("\t.global\tmodule_swi\n\t.hidden\tmodule_swi\n\t.type\tmodule_swi, %function\nmodule_swi:\t\t\t\t\t/* x0 = SWI offset, x1 = registers, x2 = pw */")
        dflt = m["swi_handler"]
        if per_swi:
            for i, h in enumerate(m["swi_handlers"]):
                if h and h != dflt: A("\tcmp\tw0, #%d\n\tb.ne\t1f\n\tb\t%s\n1:" % (i, h))
        if dflt: A("\tb\t%s" % dflt)
        else: A("\tmov\tx0, #-1\t\t\t\t/* error_BAD_SWI: the kernel makes the error */\n\tret")
    if m["cxx"]: A("\t.global\t__mod_cxx_init\n\t.hidden\t__mod_cxx_init\n\t.type\t__mod_cxx_init, %function\n__mod_cxx_init:\n\tb\t__modlib_cxx_init\n\t.global\t__mod_cxx_fini\n\t.hidden\t__mod_cxx_fini\n\t.type\t__mod_cxx_fini, %function\n__mod_cxx_fini:\n\tb\t__modlib_cxx_fini")
    if m["swi_decoder"]:
        if m["swi_decoder2"] is None: A("\t.global\tmodule_swi_decode\n\t.hidden\tmodule_swi_decode\n\t.type\tmodule_swi_decode, %%function\nmodule_swi_decode:\n\tb\t%s" % m["swi_decoder"])
        else: A("\t.global\tmodule_swi_name\n\t.hidden\tmodule_swi_name\n\t.type\tmodule_swi_name, %%function\nmodule_swi_name:\n\tb\t%s\n\t.global\tmodule_swi_number\n\t.hidden\tmodule_swi_number\n\t.type\tmodule_swi_number, %%function\nmodule_swi_number:\n\tb\t%s" % (m["swi_decoder"], m["swi_decoder2"]))
        A("\t.section .rodata\n\t.balign 4\n\t.global\t__mod_decode_form\n\t.hidden\t__mod_decode_form\n__mod_decode_form:\n\t.word\t%d\n\t.section .text.header, \"ax\"" % (1 if m["swi_decoder2"] is None else 2))
    if m["errors"]:                                                                  # error-identifiers: the error blocks (a number and the message) in the module, __err_NAME; the header makes pointers of them
        A("\t.section .rodata\n\t.balign 4")
        n = m["error_base"]
        for name, num, msg in m["errors"]:
            if num: use = num
            else: use = n; n += 1
            A("\t.global\t__err_%s\n\t.hidden\t__err_%s\n__err_%s:\n\t.word\t%#x\n%s\n\t.byte\t0\n\t.balign\t4" % (name, name, name, use, asm_bytes(msg)))
        A("\t.section .text.header, \"ax\"")
    A("#include \"modcore64.S\"")
    A("\t.section .text.header, \"ax\"")
    if has_svc:
        if nums: A("\tMOD_SERVICE_TABLE %s" % ", ".join("%#x" % n for n in nums))
        else: A("\tMOD_SERVICE_PLAIN")
    else: A("\t.global\t__mod_svc_numbers\n\t.hidden\t__mod_svc_numbers\n__mod_svc_numbers:\n\t.word\t0\t\t\t\t\t/* no services: the kit's runtime refers to the list */")
    return "\n".join(o) + "\n"

def main(argv):
    out_o = out_s = out_h = infile = None
    pre = False
    cpp = []
    i = 0
    while i < len(argv):
        a = argv[i]
        if a in ("-s", "-d", "-o"):
            i += 1
            if i >= len(argv): sys.exit("cmunge64: %s needs a file name" % a)
            if a == "-o": out_o = argv[i]
            elif a == "-s": out_s = argv[i]
            else: out_h = argv[i]
        elif a == "-p": pre = True
        elif a[:2] in ("-D", "-U", "-I") and len(a) > 2: cpp.append(a)
        elif a in ("-h", "--help"): print(__doc__); return 0
        elif a.startswith("-"): sys.exit("cmunge64: unknown option %s" % a)
        elif infile is None: infile = a
        else: sys.exit("cmunge64: more than one input file")
        i += 1
    if infile is None: sys.exit("cmunge64: no input file (cmunge64.py -h)")
    mk = load_mkmodhdr()
    text = open(infile, "rb").read()
    if pre:
        r = subprocess.run([CC, "-E", "-P", "-x", "assembler-with-cpp"] + cpp + [infile], capture_output=True)
        if r.returncode: sys.stderr.write(r.stderr.decode("latin-1")); sys.exit("cmunge64: the preprocessor failed on %s" % infile)
        text = r.stdout
    try:
        m = mk["parse"](text.decode("latin-1"))
        bad = [k for k, v in (("irq-handlers/vector-handlers/generic-veneers/vector-traps/event-handler", m["veneers"]), ("pdriver-handler", m["pdriver"]), ("module-is-runnable", m["runnable"]),
                              ) if v]
        if bad: sys.exit("cmunge64: %s: %s: not supported for AArch64 yet" % (infile, ", ".join(bad)))
        asm = generate_asm(mk, m, infile)
        h = mk["generate_h"](m, infile, os.path.basename(infile))
        h = h.replace("extern void __err_", "extern void __attribute__ ((visibility (\"hidden\"))) __err_").replace("(_kernel_oserror*)(int)__err_", "(_kernel_oserror*)(long)__err_")
    except mk["CmhgError"] as e:
        sys.exit("cmunge64: %s: %s" % (infile, e))
    base = os.path.splitext(infile)[0]
    s_name = out_s or (None if out_o else base + "_hdr.S")
    tmp = tempfile.mkdtemp(prefix="cmunge64-")
    try:
        if s_name or out_o:
            sp = s_name or os.path.join(tmp, "module.S")
            open(sp, "w").write(asm)
            if out_o:
                sys.path.insert(0, HERE)
                if MODCC: r = subprocess.run([MODCC, "-mmodule", "-c", sp, "-o", out_o])
                else:
                    mf = re.search(r'MODFLAGS="([^"]*)"', open(os.path.join(HERE, "modflags.sh")).read()).group(1).split()
                    r = subprocess.run([CC] + mf + ["-I" + HERE, "-I" + os.path.join(HERE, "include"), "-c", sp, "-o", out_o])
                if r.returncode: return r.returncode
        open(out_h or base + "_hdr.h", "w").write(h)
    finally:
        import shutil; shutil.rmtree(tmp, ignore_errors=True)
    return 0

sys.exit(main(sys.argv[1:]))
